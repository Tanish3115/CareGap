import { test, expect } from "@playwright/test";
import { openSection } from "./navigation";

test("patients confirm deletion of documents, reports, records and individual follow-ups", async ({ page }) => {
  test.setTimeout(120000);
  const email = `synthetic-delete-features-${Date.now()}@example.com`;
  const signup = await page.request.post('/api/v1/auth/register', { data: { email, password: 'SyntheticDelete123!', full_name: 'Synthetic Deletion Patient', role: 'patient' } });
  expect(signup.status()).toBe(201);
  await page.request.post('/api/v1/auth/login', { data: { email, password: 'SyntheticDelete123!' } });
  const me = await (await page.request.get('/api/v1/auth/me')).json();
  const uploaded = await page.request.post('/api/v1/documents/upload', { multipart: { title: 'Synthetic disposable image', document_type: 'other', file: { name:'synthetic.png', mimeType:'image/png', buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAABQAAAAUCAIAAAAC64paAAAALElEQVR4nGP8//8/A7mAiWydDKOaSQZMpGtBgFHNJAImUjUgg1HNJAKKAgwAnKADJa4TmNgAAAAASUVORK5CYII=', 'base64') } } });
  expect(uploaded.status()).toBe(201);
  const doc = (await uploaded.json()).document;
  await expect.poll(async () => (await (await page.request.get(`/api/v1/documents/${doc.id}/processing`)).json()).status, { timeout: 20000 }).not.toBe('processing');
  await page.goto('/dashboard#documents');
  await page.getByRole('button', { name:'Delete document', exact:true }).click();
  const documentForm = page.getByRole('form', { name:'Delete document', exact:true });
  await documentForm.getByRole('button', { name:'Cancel deletion', exact:true }).click();
  expect((await page.request.get(`/api/v1/documents/${doc.id}`)).status()).toBe(200);
  // Wait for terminal processing so the reviewed deletion token remains current.
  await expect.poll(async () => (await (await page.request.get(`/api/v1/documents/${doc.id}/processing`)).json()).status, { timeout: 20000 }).toMatch(/succeeded|failed/);
  await page.getByRole('button', { name:'Delete document', exact:true }).click();
  await documentForm.getByRole('checkbox').check();
  await documentForm.getByRole('button', { name:'Delete permanently', exact:true }).click();
  await expect(page.getByRole('heading', { name:'Synthetic disposable image', exact:true })).toBeHidden();
  expect((await page.request.get(`/api/v1/documents/${doc.id}/download`)).status()).toBe(404);
  await expect(page.getByRole('heading', { name:'Documents', exact:true })).toBeVisible();
  await expect.poll(async () => (await (await page.request.get('/api/v1/patient-file-deletions')).json())[0]?.status, { timeout:20000 }).toBe('done');
  await page.getByText('Deleted document file cleanup', { exact:true }).click();
  await page.getByRole('button', { name:'Refresh file cleanup status', exact:true }).click();
  await expect(page.getByText('File cleanup completed', { exact:true })).toBeVisible();
  const account = await (await page.request.post('/api/v1/clinical/medication-use', { data: { patient_id:me.patient.id, name:'SYNTHETIC-DELETE', use_status:'unknown', reported_on:'2026-01-01', reason:'Synthetic deletion flow' } })).json();
  const health = await (await page.request.post('/api/v1/clinical/records', { data:{ patient_id:me.patient.id, title:'Synthetic disposable lab', occurred_on:'2026-01-01', data:{ kind:'lab', test_name:'Synthetic test', value:'Synthetic result' }, reason:'Synthetic source reviewed', source_checked:true, source_document_ids:[] } })).json();
  const consultation = await (await page.request.post('/api/v1/clinical/encounters', { data:{ patient_id:me.patient.id, title:'Synthetic retained consultation', notes:'Synthetic notes', occurred_on:'2026-01-01' } })).json();
  const follow = await (await page.request.post('/api/v1/clinical/follow-ups', { data:{ encounter_id:consultation.id, title:'Synthetic disposable follow-up', due_on:'2026-01-02' } })).json();
  // Reload so every mounted workspace reads the newly seeded synthetic records.
  await page.reload();
  await openSection(page, 'medications');
  await page.getByRole('button', { name:/SYNTHETIC-DELETE.*Use uncertain/ }).click();
  await page.getByRole('button', { name:'Delete medication report', exact:true }).click();
  const medicationForm = page.getByRole('form', { name:'Delete medication report', exact:true });
  await medicationForm.getByRole('checkbox').check();
  await medicationForm.getByRole('button', { name:'Delete permanently', exact:true }).click();
  await expect(page.getByRole('button', { name:/SYNTHETIC-DELETE.*Use uncertain/ })).toBeHidden();
  expect((await page.request.get(`/api/v1/clinical/medication-use/${account.id}/history`)).status()).toBe(404);
  await openSection(page, 'records');
  await page.getByRole('button', { name:/Synthetic disposable lab/ }).click();
  await page.getByRole('button', { name:'Delete health record', exact:true }).click();
  const recordForm = page.getByRole('form', { name:'Delete health record', exact:true });
  await recordForm.getByRole('checkbox').check();
  await recordForm.getByRole('button', { name:'Delete permanently', exact:true }).click();
  await expect(page.getByRole('button', { name:/Synthetic disposable lab/ })).toBeHidden();
  expect((await page.request.get(`/api/v1/clinical/records/${health.id}/history`)).status()).toBe(404);
  await openSection(page, 'consultations');
  await page.getByRole('button', { name:'Delete follow-up', exact:true }).click();
  const followForm = page.getByRole('form', { name:'Delete follow-up', exact:true });
  await followForm.getByRole('checkbox').check();
  await followForm.getByRole('button', { name:'Delete permanently', exact:true }).click();
  await expect(page.getByRole('button', { name:'Synthetic retained consultation', exact:true })).toBeVisible();
  await expect(page.getByRole('region', { name:'Follow-up list', exact:true }).getByText('Synthetic disposable follow-up', { exact:true })).toHaveCount(0);
  expect((await page.request.get(`/api/v1/clinical/follow-ups/${follow.id}/history`)).status()).toBe(404);
  expect((await page.request.get(`/api/v1/clinical/encounters/${consultation.id}`)).status()).toBe(200);
});
